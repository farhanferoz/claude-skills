#!/usr/bin/env bash
# Commit-provenance guard (PreToolUse, Bash).
#
# WHY THIS IS A HOOK AND NOT A RULE
# ~/.claude/CLAUDE.md bans AI/tool provenance in anything committed or shared.
# The harness's OWN Bash tool description instructs the model to end every commit
# message with a `Co-Authored-By: Claude ...` trailer, and every PR body with
# "Generated with [Claude Code]". Two instruction sources in direct conflict --
# and a worker resolves it toward the TOOL DESCRIPTION, because that is the one
# attached to the tool it is invoking.
#
# Observed 2026-07-15: commit e827b65c, a Haiku worker, added the trailer despite
# a brief that banned it (caught and amended before push). Same shape as the
# idle-guard that made workers self-assign from the task list -- the instruction
# was there in black and white, and no brief survives it. A tools: allowlist does
# not contain this either. A brief does not bind against a tool description.
# Only a hook binds.
#
# SCOPE: `git commit` invocations, and `gh pr create` / `gh pr edit` -- the two
# commands that WRITE a PR body -- whose message or body carries a trailer-shaped
# provenance marker. A prose mention ("drop the Co-Authored-By trailer") does NOT
# match -- the patterns require the `: Claude` / `@anthropic` / "Generated with
# [Claude" shape. Reading the text out of `-F <file>` or `--body-file <file>` is
# supported; a `-F -` heredoc body already sits in the command string.
# `gh pr view` (reads a body) and `gh issue create` are deliberately NOT matched.
#
# FILE CONTENT (Write|Edit) added 2026-08-13 -- the third surface, and the one
# that was never covered. CLAUDE.md names it in as many words: the rule "covers
# NOTHING ELSE, so this rule still binds for PR titles/descriptions, CODE
# COMMENTS, CHANGELOGS, and research reports/PDFs meant for colleagues." Commits
# and PR bodies were guarded; authored file content was not, so a byline in a
# report, a `// Generated by Claude` comment, or a badge at the foot of a
# CHANGELOG entry had nothing but attention standing in its way. A PARTIAL shadow
# is worse than none: the guard's existence reads as coverage.
#
# The file patterns are ANCHORED (trailer at start of line) rather than the
# looser command patterns, because authored prose legitimately discusses this
# rule. Measured 2026-08-13 against the three files that document it most
# heavily -- ~/.claude/CLAUDE.md, main-session-doctrine.md and the
# feedback_no_ai_attribution memory note: ZERO matches on all three. The only
# self-hit is this script (two prose mentions of the badge), so it exempts its
# own source and log by path -- otherwise it could never be edited again.
#
# NATIVE PRIOR ART, checked 2026-08-13 (code.claude.com/docs/en/settings): the
# `attribution` setting -- `{"attribution": {"commit": "", "pr": ""}}` -- stops
# the harness EMITTING commit/PR provenance at source, which is strictly better
# than blocking it afterwards, and it is now set. `includeCoAuthoredBy` is the
# deprecated older key, and was reported not to be respected
# (anthropics/claude-code#7543), so this hook stays as the backstop for that half
# AND is the only mechanism at all for the file-content half, which no setting
# covers.
#
# The PR half was added 2026-08-13 after an audit of the 2.1.229 system prompt
# found the badge instruction sitting in the same tool description as the trailer,
# with only the commit half guarded. LIVE-FIRED that day against the shape a real
# PR actually takes -- `gh pr create --title ... --body "$(cat <<'EOF' ... EOF)"`
# with the badge inside the heredoc -- and it denied (rc=2, logged `kind=PR body`),
# not merely against the synthetic `--body '<literal>'` the matrix uses.
#
# Fail-open by design: any parse error, missing jq, or unreadable input -> allow.
# Escape hatch: CCLAUDE_PROVENANCE_MODE=observe   (log, do not block).
# Audit trail:  $CLAUDE_CONFIG_DIR/commit_provenance_guard.log
set -uo pipefail

input="$(cat 2>/dev/null)" || exit 0
command -v jq >/dev/null 2>&1 || exit 0
tool="$(printf '%s' "$input" | jq -r '.tool_name // empty' 2>/dev/null)" || exit 0

# ---- Write|Edit: authored file content -------------------------------------
# Handled first and returns on its own; the Bash path below is unchanged.
case "$tool" in
Write|Edit|MultiEdit)
  file="$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty' 2>/dev/null)"
  # This guard's own source and log carry the patterns as documentation. Without
  # the exemption the guard would permanently block edits to itself.
  case "$file" in
    */commit_provenance_guard.sh|*/commit_provenance_guard.log) exit 0 ;;
  esac
  # Only the text BEING WRITTEN is scanned -- never the file's existing content,
  # so a pre-existing marker somewhere else in the file is not this write's fault.
  scan="$(printf '%s' "$input" | jq -r '
      [ .tool_input.content, .tool_input.new_string, (.tool_input.edits[]?.new_string) ]
      | map(select(. != null)) | join("\n")' 2>/dev/null)"
  [ -z "${scan:-}" ] && exit 0

  # Anchored trailer + the badge/e-mail shapes. See the header for the measured
  # false-positive check behind the anchoring.
  FPATTERN='^[[:space:]]*co-authored-by:[[:space:]]*claude'
  FPATTERN="$FPATTERN"'|^[[:space:]]*co-authored-by:.*@anthropic'
  FPATTERN="$FPATTERN"'|noreply@anthropic\.com'
  FPATTERN="$FPATTERN"'|generated[[:space:]]+with[[:space:]]*\[?claude'
  FPATTERN="$FPATTERN"'|🤖[[:space:]]*generated[[:space:]]+with'

  fhit="$(printf '%s' "$scan" | grep -Eio "$FPATTERN" | sort -u | head -3 | tr '\n' ';')"
  flog="${CLAUDE_CONFIG_DIR:-$HOME/.claude}/commit_provenance_guard.log"
  if [ -z "$fhit" ]; then
    printf '%s ALLOW kind=file content file=%s\n' "$(date -Is)" "$file" >> "$flog" 2>/dev/null || true
    exit 0
  fi
  printf '%s %s kind=file content file=%s hit=%s\n' "$(date -Is)" \
    "${CCLAUDE_PROVENANCE_MODE:-block}" "$file" "$fhit" >> "$flog" 2>/dev/null || true
  [ "${CCLAUDE_PROVENANCE_MODE:-}" = "observe" ] && exit 0

  cat >&2 <<MSG
PROVENANCE GUARD — BLOCKED. This file content carries AI/tool provenance.
File:    ${file}
Matched: ${fhit}

~/.claude/CLAUDE.md bans AI/tool provenance in ANYTHING committed or shared — and
names this surface explicitly: code comments, changelogs, and reports/PDFs meant for
colleagues, not just commit messages and PR bodies. Author it AS THE USER.

FIX: remove the trailer/badge/@anthropic address from the text you are writing.
Nothing else about the write is wrong.
(Writing text ABOUT the trailer? A trailer at START OF LINE is what matches — prose
that mentions it does not. If you genuinely cannot avoid the literal form, say so and
ask — do not route around this (D15).)
MSG
  exit 2
  ;;
esac

# ---- Bash: commit messages and PR bodies -----------------------------------
cmd="$(printf '%s' "$input" | jq -r '.tool_input.command // empty' 2>/dev/null)" || exit 0
[ -z "$cmd" ] && exit 0

# Two invocation families are this hook's business, because the harness's Bash
# tool description plants provenance in BOTH -- a `Co-Authored-By` trailer on
# every commit AND a "Generated with [Claude Code]" badge on every PR body
# (verified verbatim in the 2.1.229 bundle, 2026-08-13). The PR half shipped
# UNGUARDED from this hook's first day: CLAUDE.md says so in as many words
# ("covers NOTHING ELSE, so this rule still binds for PR titles/descriptions"),
# and an unguarded half of a two-part instruction is the half that lands.
#   - git commit:   `git -C <p> commit`, `git commit --amend`, `... && git commit ...`
#   - gh pr:        `gh pr create`, `gh pr edit` -- the two that WRITE a body.
# `gh pr view`, `gh issue create` and everything else: allow.
kind=""
if printf '%s' "$cmd" \
     | grep -Eq '(^|[;&|`(])[[:space:]]*git[^;&|]*[[:space:]]commit([[:space:]]|$)'; then
  kind="commit message"
fi
if printf '%s' "$cmd" \
     | grep -Eq '(^|[;&|`(])[[:space:]]*gh[[:space:]]+pr[[:space:]]+(create|edit)([[:space:]]|$)'; then
  kind="${kind:+$kind and }PR body"
fi
[ -z "$kind" ] && exit 0

# Test growth (owner, 2026-10-18): a commit whose tests grow must say why. It lives here because this hook is
# already registered in every session's settings; the logic and its reasons are in its own script.
if [ "${kind#commit message}" != "$kind" ] && command -v python3 >/dev/null 2>&1; then
  printf '%s' "$input" | python3 "$(dirname "$0")/test_growth_check.py"
  [ $? -eq 2 ] && exit 2
fi

# Text to scan = the command (covers -m, --body, and a `-F -` heredoc body),
# plus the contents of a real message/body file if one was named.
scan="$cmd"
msgfile="$(printf '%s' "$cmd" \
  | grep -oE '(-F|--file=?|--body-file=?)[[:space:]]*[^[:space:];&|]+' \
  | head -1 | sed -E 's/^(-F|--file=?|--body-file=?)[[:space:]]*//')"
if [ -n "${msgfile:-}" ] && [ "$msgfile" != "-" ] && [ -r "$msgfile" ]; then
  scan="$scan
$(cat "$msgfile" 2>/dev/null)"
fi

# Trailer-shaped provenance ONLY -- deliberately not a bare "claude" match.
PATTERN='co-authored-by:[[:space:]]*claude'
PATTERN="$PATTERN"'|co-authored-by:.*@anthropic'
PATTERN="$PATTERN"'|noreply@anthropic\.com'
PATTERN="$PATTERN"'|generated[[:space:]]+with[[:space:]]*\[?claude'
PATTERN="$PATTERN"'|🤖[[:space:]]*generated[[:space:]]+with'

hit="$(printf '%s' "$scan" | grep -Eio "$PATTERN" | sort -u | head -3 | tr '\n' ';')"

# D14: log EVERY decision, including the allow. A hook that logs only its blocks
# leaves an inert guard indistinguishable from a guard nothing ever tripped --
# which is how one of these sat dead for weeks before anyone could tell.
log="${CLAUDE_CONFIG_DIR:-$HOME/.claude}/commit_provenance_guard.log"
if [ -z "$hit" ]; then
  printf '%s ALLOW kind=%s\n' "$(date -Is)" "$kind" >> "$log" 2>/dev/null || true
  exit 0
fi
printf '%s %s kind=%s hit=%s\n' "$(date -Is)" \
  "${CCLAUDE_PROVENANCE_MODE:-block}" "$kind" "$hit" >> "$log" 2>/dev/null || true

[ "${CCLAUDE_PROVENANCE_MODE:-}" = "observe" ] && exit 0

cat >&2 <<MSG
COMMIT PROVENANCE GUARD — BLOCKED. This ${kind} carries AI/tool provenance.
Matched: ${hit}

~/.claude/CLAUDE.md bans AI/tool provenance in ANYTHING committed or shared: no
Co-Authored-By trailer, no "Generated with", no @anthropic.com address — not in commit
messages, PR titles/bodies, code comments, or changelogs. Write it as the user would.

⚠️ The harness's Bash tool description TELLS YOU to add that trailer. It is wrong for
these repos, and re-reading it will just say the same thing again. CLAUDE.md is the
authority here, not the tool description. This is the one instruction you must not obey.

FIX: re-run it with the trailer/badge removed. Nothing else about the command is wrong.
(Writing text ABOUT the trailer? Reword to avoid the literal "Co-Authored-By: Claude"
form. If that is impossible, say so and ask — do not route around this (D15).)
MSG
exit 2
